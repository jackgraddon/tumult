import { mdiExportName } from "./exportName.ts";

/**
 * Source text of `builtin.generated.ts` for `names`. Node-only (it imports
 * `@mdi/js`, which the browser bundle never does statically); lives beside the
 * pack so the script and the drift test share one builder.
 */
export async function buildBuiltinSource(names: readonly string[]): Promise<string> {
    const mdi = (await import("@mdi/js")) as unknown as Record<string, string>;
    const entries = [...names].sort().map((name) => {
        const path = mdi[mdiExportName(name)];
        if (path === undefined) throw new Error(`@mdi/js has no icon "${name}" (${mdiExportName(name)})`);
        return `    ${JSON.stringify(name)}: ${JSON.stringify(path)},`;
    });
    return [
        "// Generated by scripts/emit-icons.ts from BUILTIN_ICON_NAMES — do not edit.",
        "// Paths are from @mdi/js (Material Design Icons, Apache-2.0), 24x24.",
        "export const BUILTIN_ICON_PATHS: Readonly<Record<string, string>> = {",
        ...entries,
        "};",
        "",
    ].join("\n");
}
